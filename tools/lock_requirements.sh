#!/usr/bin/env bash
# Locks the Python dependencies: each requirements*.in becomes a requirements*.txt with every
# package, transitive ones included, pinned to one version and to the SHA-256 of each of its
# published files (docs/SUPPLY_CHAIN.md). The images install the .txt files with
# pip --require-hashes, so a build gets exactly these files or fails.
#
#   tools/lock_requirements.sh            # re-lock every .in file after editing one
#   tools/lock_requirements.sh server/requirements.in      # that one only
#
# Runs pip-compile in a throwaway container of the same Python image the Dockerfiles use
# (its digest is read from server/Dockerfile), so the lock is resolved for Linux and
# Python 3.12, whatever machine runs this. Talks to PyPI only. Review the diff before
# committing it: a new package or a new hash is a change to what runs in production.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PIP_TOOLS_VERSION=7.6.2

base="$(sed -n 's/^FROM \(python:[^ ]*@sha256:[0-9a-f]\{64\}\).*/\1/p' "$ROOT/server/Dockerfile" | head -1)"
[ -n "$base" ] || { echo "no digest-pinned python image in server/Dockerfile" >&2; exit 1; }

# in-file (relative to the repository), and "unsafe" when the lock is for pip or setuptools.
locks=(
  "server/requirements.in"
  "server/requirements-pip.in unsafe"
  "worker/requirements-arjun.in"
  "worker/requirements-arjun-build.in unsafe"
  "tools/ci/requirements-audit.in"
)

only="${1:-}"     # optional: lock this .in file only
for entry in "${locks[@]}"; do
  set -- $entry
  in="$1"; out="${in%.in}.txt"; extra=""
  [ -z "$only" ] || [ "$only" = "$in" ] || continue
  [ "${2:-}" = unsafe ] && extra="--allow-unsafe"
  echo "[lock] $in -> $out"
  docker run --rm --network bridge -e CUSTOM_COMPILE_COMMAND="tools/lock_requirements.sh" \
    -e PIP_DISABLE_PIP_VERSION_CHECK=1 -e HOME=/tmp \
    --user "$(id -u):$(id -g)" -v "$ROOT:/src" -w /src "$base" sh -ec "
      python -m venv /tmp/pt >/dev/null
      /tmp/pt/bin/pip install -q pip-tools==$PIP_TOOLS_VERSION
      /tmp/pt/bin/pip-compile -q --generate-hashes --strip-extras --no-emit-index-url \
        --no-header $extra --output-file '$out' '$in'"
  # pip-compile writes no header with --no-header; say where the file comes from.
  { printf '# Generated by tools/lock_requirements.sh from %s. Do not edit by hand.\n' "$(basename "$in")"
    cat "$ROOT/$out"; } > "$ROOT/$out.tmp" && mv "$ROOT/$out.tmp" "$ROOT/$out"
done
